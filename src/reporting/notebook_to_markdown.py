"""Convert each notebook in notebooks/ into a markdown document in docs/notebooks/.

The markdown file keeps, in notebook order, the explanation cells (as written) and the code cells (as fenced
python blocks). Narrative that a notebook produces by code (text/markdown outputs, e.g. notebook 10) is kept
as explanation. Other outputs are left out by default; add --with-outputs to append short text outputs.

Run from the project root:  python3 -m src.reporting.notebook_to_markdown [--with-outputs]
The notebooks themselves are never modified.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NB_DIR = ROOT / "notebooks"
OUT_DIR = ROOT / "docs" / "notebooks"
MAX_OUTPUT_CHARS = 1500


def _text(src):
    return "".join(src) if isinstance(src, list) else src


def _fence(code, lang="python"):
    ticks = "```"
    while ticks in code:
        ticks += "`"
    return f"{ticks}{lang}\n{code.rstrip()}\n{ticks}"


def _outputs(cell, with_outputs):
    parts = []
    for o in cell.get("outputs", []):
        if o["output_type"] in ("display_data", "execute_result"):
            data = o["data"]
            if "text/markdown" in data:                       # narrative generated by code: keep as explanation
                parts.append(("md", _text(data["text/markdown"]).strip()))
            elif with_outputs and "text/plain" in data:
                parts.append(("out", _text(data["text/plain"])))
        elif o["output_type"] == "stream" and with_outputs:
            parts.append(("out", _text(o["text"])))
    return parts


def convert(nb_path, with_outputs=False):
    nb = json.loads(nb_path.read_text(encoding="utf-8"))
    out = [f"<!-- Generated from notebooks/{nb_path.name} by src/reporting/notebook_to_markdown.py. Do not edit by hand. -->", ""]
    n_code = n_md = 0
    for cell in nb["cells"]:
        src = _text(cell["source"]).strip()
        if cell["cell_type"] == "markdown" and src:
            out += [src, ""]
            n_md += 1
        elif cell["cell_type"] == "code" and src:
            out += [_fence(src), ""]
            n_code += 1
            for kind, text in _outputs(cell, with_outputs):
                if kind == "md":
                    out += [text, ""]
                else:
                    text = text.rstrip()
                    if len(text) > MAX_OUTPUT_CHARS:
                        text = text[:MAX_OUTPUT_CHARS] + "\n... (truncated)"
                    out += ["Output:", "", _fence(text, "text"), ""]
    return "\n".join(out).rstrip() + "\n", n_md, n_code


def main():
    with_outputs = "--with-outputs" in sys.argv
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for nb_path in sorted(NB_DIR.glob("*.ipynb")):
        text, n_md, n_code = convert(nb_path, with_outputs)
        (OUT_DIR / (nb_path.stem + ".md")).write_text(text, encoding="utf-8")
        title = next((l.lstrip("# ").strip() for l in text.splitlines() if l.startswith("# ")), nb_path.stem)
        rows.append((nb_path.stem, title, n_md, n_code))
        print(f"{nb_path.stem:40s} explanation cells {n_md:3d}  code cells {n_code:3d}  {len(text):7d} chars")
    index = ["# Notebook Documents", "",
             "One markdown document per notebook: the explanations and the code, in notebook order. "
             "They are generated from the notebooks by `python3 -m src.reporting.notebook_to_markdown` "
             "(the notebooks are not modified). Code-only copies of the notebooks (no explanation cells, outputs kept) are in "
             "`notebooks/code_only/`, created by `python3 -m src.reporting.make_code_only_notebooks`.", "",
             "| Notebook | Document | Title |", "|---|---|---|"]
    index += [f"| `notebooks/{s}.ipynb` | [{s}.md]({s}.md) | {t} |" for s, t, _, _ in rows]
    (OUT_DIR / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
