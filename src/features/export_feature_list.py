"""Write docs/final_features.md and reports/tables/final_feature_list.csv from the default pipeline.
Run from the project root:  python3 -m src.features.export_feature_list
The fit is used only to read column names; no data are transformed for modelling."""
import pandas as pd

from src.data.loading import load_raw
from src.features import preprocessing as P
from src.features.feature_groups import COLUMN_TO_GROUP


def main():
    X = load_raw().drop(columns=["SalePrice", "Id"])
    pipe = P.build_preprocessor("baseline").fit(X)
    ct = pipe.named_steps["encode"]
    Z = pipe.transform(X)
    rows = []
    for name, _, cols in ct.transformers_:
        if name == "remainder":
            continue
        if name == "nominal":
            for src in cols:
                outs = [c for c in Z.columns if c.startswith(src + "_")]
                rows.append(("nominal (one-hot)", src, len(outs), ", ".join(o[len(src) + 1:] for o in outs)))
        else:
            rows += [(name, c, 1, "") for c in cols]
    t = pd.DataFrame(rows, columns=["kind", "source attribute", "output columns", "levels (one-hot only)"])
    t["category"] = t["source attribute"].map(lambda c: COLUMN_TO_GROUP.get(c, "Engineered"))
    order = {"numeric": 0, "ordinal": 1, "binary": 2, "nominal (one-hot)": 3, "flags": 4}
    t = t.sort_values("kind", key=lambda s: s.map(order), kind="stable")
    t.to_csv("reports/tables/final_feature_list.csv", index=False)
    lst = lambda k: ", ".join(f"`{c}`" for c in t[t.kind == k]["source attribute"])
    n = lambda k: int((t.kind == k).sum())
    nom = t[t.kind == "nominal (one-hot)"]
    removed = P.SALE_CONTEXT + P.IDENTIFIERS_AND_TARGET + P.ALWAYS_DROP_FEATURES + sorted(P.LOW_INFORMATION) + ["YearBuilt", "YearRemodAdd"] + sorted(P.REDUNDANT)
    md = f"""# Final Attributes After Preprocessing

Generated by `python3 -m src.features.export_feature_list` from `build_preprocessor("baseline")` (defaults: `scale="robust"`, `neighborhood_encoding="onehot"`, `reduce_redundancy=True`). The pipeline turns the 79 raw predictors into **{Z.shape[1]} model-ready columns** built from **{len(t)} attributes**. Per-attribute table: `reports/tables/final_feature_list.csv`.

| Kind | Source attributes | Output columns |
|---|---|---|
| Numeric (median-imputed, skewed ones `log1p`, robust-scaled) | {n('numeric')} | {n('numeric')} |
| Ordinal (ordered integer codes, robust-scaled) | {n('ordinal')} | {n('ordinal')} |
| Binary (0/1) | {n('binary')} | {n('binary')} |
| Nominal (one-hot) | {n('nominal (one-hot)')} | {int(nom['output columns'].sum())} |
| Flags (0/1) | {n('flags')} | {n('flags')} |
| **Total** | **{len(t)}** | **{Z.shape[1]}** |

## Numeric ({n('numeric')})
{lst('numeric')}

Engineered numeric features kept: `TotalBathrooms`, `HouseAge`, `RemodAge`.

## Ordinal ({n('ordinal')})
{lst('ordinal')}

## Binary ({n('binary')})
{lst('binary')}

## Nominal, one-hot encoded ({n('nominal (one-hot)')} attributes)
""" + "\n".join(f"- `{r['source attribute']}`: {r['output columns']} columns" for _, r in nom.iterrows()) + f"""

Levels with fewer than 10 training rows share one `<attribute>_infrequent_sklearn` column. `MSSubClass` is treated as nominal.

## Flags ({n('flags')})
{lst('flags')} (engineered). `LotFrontage_Missing` is added only by the `neighborhood_indicator` strategy.

## Removed ({len(removed)} columns, not in the output)
- **Identifier and target:** `Id`, `SalePrice`.
- **Sale context (unknown at listing time):** {', '.join(f'`{c}`' for c in P.SALE_CONTEXT)}.
- **Low information (EDA F10, F11):** {', '.join(f'`{c}`' for c in sorted(P.LOW_INFORMATION))}.
- **Inconsistent / redundant with another year column:** `GarageYrBlt`.
- **Replaced by engineered age features:** `YearBuilt` (-> `HouseAge`), `YearRemodAdd` (-> `RemodAge`).
- **Redundant (`reduce_redundancy=True`):** {', '.join(f'`{c}`' for c in sorted(P.REDUNDANT))}. `TotalSF` is created and then removed.
"""
    open("docs/final_features.md", "w").write(md)
    print(Z.shape, len(t))


if __name__ == "__main__":
    main()
